n = int(input())

tens = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят"]
ones = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]

if n % 10 == 0:
    print(tens[n // 10], "лет")
elif n % 10 == 1:
    print(tens[n // 10], ones[n % 10], "год")
elif n % 10 in (2, 3, 4):
    print(tens[n // 10], ones[n % 10], "года")
else:
    print(tens[n // 10], ones[n % 10], "лет")
